#include <iostream>
using namespace std;
int main() {
    int age = 22;
    int marks = 100;
    char grade = 'A';
    bool isAdult = true;
    float cgpa = 8.9;
    cout << age << " " << marks << " " << grade << " " << isAdult << " " << cgpa << endl;

    cout << "size of int : " << sizeof(int) << endl;
    cout << "size of char : " << sizeof(char) << endl;
    cout << "size of bool :" << sizeof(bool) << endl;
    cout << "size of float :" << sizeof(float) << endl;

    return 0;
}
