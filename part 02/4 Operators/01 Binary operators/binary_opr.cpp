//  Binary ->
// 1 arithmetic operators

#include <iostream>
using namespace std;
int main() {
    int a = 7;
    int b = 3;
    cout << "+ " << (a + b) << endl; // 10
    cout << "- " << (a - b) << endl; // 4
    cout << "* " << (a * b) << endl; // 21
    cout << "/ " << (a / b) << endl; // 2
    cout << "% " << (a % b) << endl; // 1

    return 0;
}
