
#include <iostream>
using namespace std;

int main() {

    //  the relational operators are
    int x;
    int y;
    cout << " Enter the number :" << endl;
    cin >> x;
    cin >> y;
    //  compare to value
    cout << (x == y) << endl;
    //  not equal to
    cout << (x != y) << endl;
    // greater than equal to
    cout << (x >= y) << endl;
    //  less than equal to
    cout << (x <= y) << endl;
    // greater than
    cout << (x > y) << endl;
    //  less than
    cout << (x < y) << endl;

    return 0;
}
