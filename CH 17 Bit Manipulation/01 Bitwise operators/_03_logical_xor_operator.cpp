//  bitwise xor operator
#include <iostream>
using namespace std;

int main() {
    //  bitwise -> ^
    int a = 10;                                      // 1010
    int b = 15;                                      // 1111
    int c = a ^ b;                                   // 0101
    cout << "bitwise and operation : " << c << endl; // 5 (0101)

    return 0;
}
